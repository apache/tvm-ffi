use std::any::TypeId;
use std::marker::PhantomData;

use tvm_ffi_sys::TVMFFITypeIndex as TypeIndex;

use crate::{AnyCompatible, AnyView};

/// A call-site-local arm number generated by `match_any!`.
#[doc(hidden)]
pub type ArmId = u32;

impl<'a, T> From<&'a crate::MutationView<'_, T>> for AnyView<'a> {
    #[inline(always)]
    fn from(value: &'a crate::MutationView<'_, T>) -> Self {
        value.as_any_view()
    }
}

/// Own the scrutinee before selecting its source adapter.
#[doc(hidden)]
pub struct SourceProbe<T>(Option<T>);
impl<T> SourceProbe<T> {
    #[inline(always)]
    pub fn new(value: T) -> Self {
        Self(Some(value))
    }
}

#[doc(hidden)]
pub struct ViewSource<'a>(AnyView<'a>);
#[doc(hidden)]
pub struct MutationSource<'a>(crate::MutationView<'a>);

/// An owned scrutinee stays in the probe and is viewed in place.
#[doc(hidden)]
pub trait PrepareSource {
    fn prepare(&mut self) -> ViewSource<'_>;
}
impl<T> PrepareSource for SourceProbe<T>
where
    for<'a> AnyView<'a>: From<&'a T>,
{
    #[inline(always)]
    fn prepare(&mut self) -> ViewSource<'_> {
        ViewSource(self.0.as_ref().unwrap().into())
    }
}
impl<'a> SourceProbe<AnyView<'a>> {
    #[inline(always)]
    pub fn prepare(&mut self) -> ViewSource<'a> {
        ViewSource(self.0.take().unwrap())
    }
}
impl<'a, T: ?Sized> SourceProbe<&'a T> {
    #[inline(always)]
    pub fn prepare<'out>(&mut self) -> ViewSource<'out>
    where
        AnyView<'out>: From<&'a T>,
    {
        ViewSource(self.0.take().unwrap().into())
    }
}
impl<'a, T> SourceProbe<crate::MutationView<'a, T>> {
    #[inline(always)]
    pub fn prepare(&mut self) -> MutationSource<'a> {
        MutationSource(self.0.take().unwrap().into_untyped())
    }
}

#[doc(hidden)]
pub trait SourceView {
    fn view(&self) -> AnyView<'_>;
    /// The source's own cell, which a reference pattern borrows in place.
    fn cell(&self) -> &crate::tvm_ffi_sys::TVMFFIAny;
}
impl SourceView for ViewSource<'_> {
    #[inline(always)]
    fn view(&self) -> AnyView<'_> {
        self.0
    }
    #[inline(always)]
    fn cell(&self) -> &crate::tvm_ffi_sys::TVMFFIAny {
        self.0.as_raw_ffi_any()
    }
}
impl SourceView for MutationSource<'_> {
    #[inline(always)]
    fn view(&self) -> AnyView<'_> {
        self.0.as_any_view()
    }
    #[inline(always)]
    fn cell(&self) -> &crate::tvm_ffi_sys::TVMFFIAny {
        self.0.cell()
    }
}

/// Type-directed matching. A matched value never consumes the source: a
/// typed mutation view aliases it, and the macro never touches the source
/// after an arm accepts, so a rejected guard needs no recovery.
#[doc(hidden)]
pub trait MatchPattern<S>: Sized {
    fn try_match(source: S) -> Option<Self>;
}
impl<'b, T: crate::type_traits::ContainerElement, S: SourceView> MatchPattern<&'b mut S> for T {
    #[inline(always)]
    fn try_match(source: &'b mut S) -> Option<Self> {
        let view = source.view();
        let data = view.as_raw_ffi_any();
        unsafe {
            (T::container_check_any_strict(data) && T::container_match_constraints(data))
                .then(|| T::container_copy_from_any_view_after_check(data))
        }
    }
}
impl<'a, 'b, 'out> MatchPattern<&'b mut ViewSource<'a>> for AnyView<'out>
where
    'a: 'out,
{
    #[inline(always)]
    fn try_match(source: &'b mut ViewSource<'a>) -> Option<Self> {
        Some(source.0)
    }
}
impl<'a, 'b> MatchPattern<&'b mut MutationSource<'a>> for AnyView<'b> {
    #[inline(always)]
    fn try_match(source: &'b mut MutationSource<'a>) -> Option<Self> {
        Some(source.view())
    }
}
impl<'a, 'b, T: crate::type_traits::ContainerElement> MatchPattern<&'b mut MutationSource<'a>>
    for crate::MutationView<'a, T>
{
    #[inline(always)]
    fn try_match(source: &'b mut MutationSource<'a>) -> Option<Self> {
        // SAFETY: the macro-private source is never used after an arm accepts
        // this view, so the alias stays the only live handle.
        unsafe { source.0.alias() }.downcast::<T>().ok()
    }
}

#[doc(hidden)]
pub struct PatternConversionProbe<T>(PhantomData<fn() -> T>);
impl<T> PatternConversionProbe<T> {
    #[doc(hidden)]
    pub const fn new() -> Self {
        Self(PhantomData)
    }
}

#[doc(hidden)]
pub trait RefPatternMetadata {
    type LeafPattern;
    fn leaf_pattern(&self) -> PhantomData<Self::LeafPattern> {
        PhantomData
    }
}
impl<T: crate::object::ObjectCore> RefPatternMetadata for &&PatternConversionProbe<T> {
    type LeafPattern = BorrowedLeaf<T>;
}
impl<T> RefPatternMetadata for &PatternConversionProbe<T> {
    type LeafPattern = T;
}

#[doc(hidden)]
pub trait RefPatternConversion<'b, S, T> {
    type Holder: std::borrow::Borrow<T>;
    fn try_convert_ref(&self, source: &'b mut S) -> Option<Self::Holder>;
}
impl<'b, T: crate::type_traits::DowncastRefFromAny + 'static, S: SourceView>
    RefPatternConversion<'b, S, T> for &&PatternConversionProbe<T>
{
    type Holder = &'b T;
    #[inline(always)]
    fn try_convert_ref(&self, source: &'b mut S) -> Option<Self::Holder> {
        // Borrow the source's own cell, which lives for 'b: a reference type
        // such as `&Add` points into the cell, an object type into the heap.
        let node = unsafe { T::downcast_ref_from_any(source.cell()) }? as *const T;
        // SAFETY: the checked value is borrowed from source for 'b, and the arm
        // does not modify a list or dict holding it (the `match_any!`
        // contract). No owning conversion or view transfer can occur while this
        // borrow lives.
        Some(unsafe { &*node })
    }
}
impl<'b, S: 'b, T: MatchPattern<&'b mut S>> RefPatternConversion<'b, S, T>
    for &PatternConversionProbe<T>
{
    type Holder = T;
    #[inline(always)]
    fn try_convert_ref(&self, source: &'b mut S) -> Option<T> {
        T::try_match(source)
    }
}

/// Runtime type-index lookup for one `match_any!` call site.
///
/// The smallest pattern `TypeIndex` is used as the base of a direct table.
/// A successful lookup returns the matching position as a call-site-local
/// [`ArmId`]. Arm bodies remain native branches in the macro expansion and are
/// never stored as functions or closures.
#[doc(hidden)]
pub struct LeafLookupTable {
    pattern_list_id: TypeId,
    base: i32,
    arm_ids: Box<[ArmId]>,
}

const NO_ARM_ID: ArmId = ArmId::MAX;

impl LeafLookupTable {
    #[doc(hidden)]
    #[cold]
    #[inline(never)]
    pub fn build(pattern_list_id: TypeId, type_indices: &[i32]) -> Self {
        assert!(
            !type_indices.is_empty(),
            "match_any! leaf lookup requires at least one arm"
        );
        assert!(
            type_indices
                .iter()
                .all(|&type_index| type_index >= TypeIndex::kTVMFFIStaticObjectBegin as i32),
            "match_any! leaf pattern returned a non-object type index"
        );
        let min_type_index = *type_indices.iter().min().unwrap();
        let max_type_index = *type_indices.iter().max().unwrap();
        let span = usize::try_from(i64::from(max_type_index) - i64::from(min_type_index) + 1)
            .expect("match_any! leaf pattern returned an invalid type-index span");
        assert!(
            type_indices.len() <= NO_ARM_ID as usize,
            "match_any! has too many exact-leaf arms"
        );
        let mut arm_ids = vec![NO_ARM_ID; span];
        for (arm_id, &type_index) in type_indices.iter().enumerate() {
            let offset = (type_index - min_type_index) as usize;
            let slot = &mut arm_ids[offset];
            // Keep the first source arm for duplicate runtime indices.
            if *slot == NO_ARM_ID {
                *slot = arm_id as ArmId;
            }
        }

        Self {
            pattern_list_id,
            base: min_type_index,
            arm_ids: arm_ids.into_boxed_slice(),
        }
    }

    #[doc(hidden)]
    #[inline(always)]
    #[allow(clippy::result_unit_err)]
    pub fn lookup(&self, pattern_list_id: TypeId, type_index: i32) -> Result<Option<ArmId>, ()> {
        if self.pattern_list_id != pattern_list_id {
            return Err(());
        }
        let offset = type_index.wrapping_sub(self.base) as usize;
        let arm_id = self.arm_ids.get(offset).copied().unwrap_or(NO_ARM_ID);
        Ok((arm_id != NO_ARM_ID).then_some(arm_id))
    }
}

/// Type-level list used to collect leaf object-pattern metadata.
/// Its cache identity uses final object representations, so matcher lifetimes
/// never need to be static. Unknown generic/custom types use the probe fallback.
#[doc(hidden)]
pub trait LeafPatternList {
    #[doc(hidden)]
    type Key: 'static;

    #[doc(hidden)]
    const ALL_EXACT_LEAF: bool;

    /// Validate that the final payload identity describes this exact matcher.
    #[doc(hidden)]
    fn matches_key() -> bool;

    #[doc(hidden)]
    fn fill_leaf_type_indices(out: &mut [i32]);
}

impl LeafPatternList for () {
    type Key = ();
    const ALL_EXACT_LEAF: bool = true;

    #[inline(always)]
    fn matches_key() -> bool {
        true
    }

    #[inline(always)]
    fn fill_leaf_type_indices(out: &mut [i32]) {
        debug_assert!(out.is_empty());
    }
}

impl<Head, Tail> LeafPatternList for (Head, Tail)
where
    Head: AnyCompatible + crate::object::ObjectRefCore,
    Tail: LeafPatternList,
{
    type Key = (
        <Head as crate::object::ObjectRefCore>::ContainerType,
        Tail::Key,
    );
    const ALL_EXACT_LEAF: bool = Head::MATCH_ANY_EXACT
        && <Head::ContainerType as crate::object::ObjectCore>::TYPE_FINAL
        && Tail::ALL_EXACT_LEAF;

    #[inline(always)]
    fn matches_key() -> bool {
        Head::match_any_exact_type_index()
            == <Head::ContainerType as crate::object::ObjectCore>::type_index()
            && Tail::matches_key()
    }

    #[inline(always)]
    fn fill_leaf_type_indices(out: &mut [i32]) {
        let (head, tail) = out
            .split_first_mut()
            .expect("match_any! pattern metadata length mismatch");
        *head = Head::match_any_exact_type_index();
        Tail::fill_leaf_type_indices(tail);
    }
}

/// A typed mutation view arm routes as its value type.
impl<'a, Head, Tail> LeafPatternList for (crate::MutationView<'a, Head>, Tail)
where
    Head: AnyCompatible + crate::object::ObjectRefCore,
    Tail: LeafPatternList,
{
    type Key = <(Head, Tail) as LeafPatternList>::Key;
    const ALL_EXACT_LEAF: bool = <(Head, Tail) as LeafPatternList>::ALL_EXACT_LEAF;
    fn matches_key() -> bool {
        <(Head, Tail) as LeafPatternList>::matches_key()
    }
    fn fill_leaf_type_indices(out: &mut [i32]) {
        <(Head, Tail) as LeafPatternList>::fill_leaf_type_indices(out);
    }
}

/// Lifetime-free metadata for a borrowed object node pattern.
#[doc(hidden)]
pub struct BorrowedLeaf<T>(PhantomData<fn() -> T>);

impl<Head: crate::object::ObjectCore, Tail: LeafPatternList> LeafPatternList
    for (BorrowedLeaf<Head>, Tail)
{
    type Key = (Head, Tail::Key);
    const ALL_EXACT_LEAF: bool = Head::TYPE_FINAL && Tail::ALL_EXACT_LEAF;

    #[inline(always)]
    fn matches_key() -> bool {
        Tail::matches_key()
    }

    #[inline(always)]
    fn fill_leaf_type_indices(out: &mut [i32]) {
        let (head, tail) = out.split_first_mut().expect("missing leaf pattern slot");
        *head = Head::type_index();
        Tail::fill_leaf_type_indices(tail);
    }
}

/// Probe used by the macro to retain ordered matching for non-leaf patterns.
#[doc(hidden)]
pub struct LeafPatternProbe<T>(PhantomData<fn() -> T>);

impl<T> LeafPatternProbe<T> {
    #[doc(hidden)]
    pub fn prepend<Head>(self, _: PhantomData<Head>) -> LeafPatternProbe<(Head, T)> {
        LeafPatternProbe::new()
    }

    #[doc(hidden)]
    pub const fn new() -> Self {
        Self(PhantomData)
    }
}

/// Leaf metadata with an autoref fallback for non-`AnyCompatible` patterns.
#[doc(hidden)]
pub trait LeafPatternMetadata {
    #[doc(hidden)]
    fn leaf_pattern_list_id(&self) -> Option<TypeId> {
        None
    }

    #[doc(hidden)]
    fn matches_key(&self) -> bool {
        false
    }

    #[doc(hidden)]
    fn fill_leaf_type_indices(&self, _out: &mut [i32]) {}
}

impl<T> LeafPatternMetadata for &LeafPatternProbe<T> {}

impl<T: LeafPatternList> LeafPatternMetadata for LeafPatternProbe<T> {
    #[inline(always)]
    fn leaf_pattern_list_id(&self) -> Option<TypeId> {
        T::ALL_EXACT_LEAF.then(TypeId::of::<T::Key>)
    }

    #[inline(always)]
    fn matches_key(&self) -> bool {
        T::matches_key()
    }

    #[inline(always)]
    fn fill_leaf_type_indices(&self, out: &mut [i32]) {
        T::fill_leaf_type_indices(out);
    }
}
